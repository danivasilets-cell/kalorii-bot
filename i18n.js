const LETTER = 'А-Яа-яЁёЇїІіЄєҐґA-Za-z';
let trRegex = null;
function buildRegex() {
  const map = TR[LANG];
  if (!map) { trRegex = null; return; }
  const keys = [...map.keys()].filter((k) => map.get(k) !== k).sort((a, b) => b.length - a.length);
  const esc2 = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  trRegex = new RegExp(`(^|[^${LETTER}0-9])(${keys.map(esc2).join('|')})(?=$|[^${LETTER}])`, 'g');
}
/** Перевод строки целиком или по фразам. */
function tr(s) {
  if (LANG === 'ru' || !s || !/[А-Яа-яЁё]/.test(s)) return s;
  const map = TR[LANG];
  const trimmed = s.trim();
  if (map.has(trimmed)) return s.replace(trimmed, map.get(trimmed));
  if (!trRegex) buildRegex();
  return s.replace(trRegex, (m, pre, key) => pre + map.get(key));
}
