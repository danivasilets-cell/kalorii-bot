const SKIP = new Set(['SCRIPT', 'STYLE', 'TEXTAREA', 'INPUT', 'CODE']);
const doneNodes = new WeakMap();
function translateNode(root) {
  if (LANG === 'ru' || !root) return;
  if (root.nodeType === 3) { translateText(root); return; }
  if (root.nodeType !== 1 || SKIP.has(root.tagName) || (root.closest && root.closest('[data-notr]'))) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT, {
    acceptNode: (n) => (n.nodeType === 1 && (SKIP.has(n.tagName) || n.hasAttribute('data-notr')) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT),
  });
  let n = root;
  do {
    if (n.nodeType === 3) translateText(n);
    else if (n.nodeType === 1) translateAttrs(n);
  } while ((n = walker.nextNode()));
  if (root.querySelectorAll) root.querySelectorAll('input[placeholder],textarea[placeholder]').forEach(translateAttrs);
}
const doneAttrs = new WeakMap();
function translateAttrs(el) {
  let memo = doneAttrs.get(el);
  for (const a of ['placeholder', 'aria-label', 'title']) {
    const v = el.getAttribute(a);
    if (!v || !/[А-Яа-яЁё]/.test(v) || (memo && memo[a] === v)) continue;
    const t = tr(v);
    if (!memo) { memo = {}; doneAttrs.set(el, memo); }
    memo[a] = t;
    if (t !== v) el.setAttribute(a, t);
  }
}
function translateText(node) {
  const v = node.nodeValue;
  if (!v || doneNodes.get(node) === v || !/[А-Яа-яЁё]/.test(v)) return;
  const t = tr(v);
  doneNodes.set(node, t);
  if (t !== v) node.nodeValue = t;
}
let observer = null;
function startTranslator() {
  if (observer) observer.disconnect();
  if (LANG === 'ru') return;
  buildRegex();
  translateNode(document.body);
  observer = new MutationObserver((muts) => {
    for (const m of muts) {
      if (m.type === 'characterData') translateText(m.target);
      else m.addedNodes.forEach((n) => translateNode(n));
      if (m.type === 'attributes' && m.target.nodeType === 1) translateAttrs(m.target);
    }
  });
  observer.observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ['placeholder', 'aria-label', 'title'] });
}
